#!/usr/bin/env node
/** Adapted universal ECC starter. Node >=22, standard library only. */
import {
  existsSync,
  readFileSync,
  readdirSync,
  mkdirSync,
  writeFileSync,
  lstatSync,
} from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
const managedBy = 'scripts/agents/setup.mjs',
  marker = `<!-- GENERATED BY ${managedBy}; do not edit directly -->`;
const sourceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2),
  allowed = new Set(['--root', '--write', '--force', '--json', '--check']);
for (let i = 0; i < args.length; i++) {
  if (!allowed.has(args[i])) throw new Error('Unknown option');
  if (args[i] === '--root' && (!args[++i] || args[i].startsWith('--')))
    throw new Error('Missing --root');
}
const rootIndex = args.indexOf('--root'),
  target = path.resolve(rootIndex < 0 ? process.cwd() : args[rootIndex + 1]);
const write = args.includes('--write'),
  force = args.includes('--force'),
  check = args.includes('--check');
if (check && (write || force)) throw new Error('--check is read-only');
if (force && !write) throw new Error('--force requires --write');
function readJson(file, fallback) {
  if (!existsSync(file)) {
    if (fallback !== undefined) return fallback;
    throw new Error('Required JSON missing');
  }
  try {
    return JSON.parse(readFileSync(file, 'utf8').replace(/^\uFEFF/u, ''));
  } catch {
    throw new Error('Invalid JSON: ' + path.basename(file));
  }
}
const config = readJson(path.join(target, 'config/project.json'), {}),
  catalog = readJson(path.join(sourceRoot, 'agents/profiles/catalog.json'));
if (write && !existsSync(path.join(target, 'config/project.json')))
  throw new Error('Configure project before generation');
const slug = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u,
  roles = config.agents?.enabledRoles ?? Object.keys(catalog.roleSkills);
if (
  !Array.isArray(roles) ||
  new Set(roles).size !== roles.length ||
  roles.some((role) => !slug.test(role) || !Object.hasOwn(catalog.roleSkills, role))
)
  throw new Error('Unknown or unsafe role');
const ignore = new Set([
  'node_modules',
  'dist',
  'build',
  'target',
  'coverage',
  'vendor',
  'output',
  'test-results',
  'playwright-report',
]);
const manifest =
  /^(package\.json|pom\.xml|build\.gradle(?:\.kts)?|build\.sbt|Package\.swift|project\.yml|pyproject\.toml|requirements\.txt|Dockerfile|(?:docker-)?compose\.ya?ml)$/u;
function discover(base, depth = 0, found = []) {
  if (depth > 4 || found.length >= 600) return found;
  for (const entry of readdirSync(base, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (found.length >= 600) break;
    if (entry.isSymbolicLink()) continue;
    const full = path.join(base, entry.name);
    if (entry.isDirectory()) {
      if (!entry.name.startsWith('.') && !ignore.has(entry.name)) discover(full, depth + 1, found);
    } else if (entry.isFile() && manifest.test(entry.name)) found.push(full);
  }
  return found;
}
const portable = (file) => path.relative(target, file).replaceAll('\\', '/'),
  signals = [];
for (const file of discover(target)) {
  const content = readFileSync(file, 'utf8').slice(0, 90000),
    name = path.basename(file),
    add = (id, evidence) => signals.push({ id, file: portable(file), evidence });
  if (name === 'package.json') {
    const pkg = readJson(file),
      dep = { ...pkg.dependencies, ...pkg.devDependencies };
    if (Object.keys(dep).some((key) => key.startsWith('@nestjs/')))
      add('node-nest', 'NestJS dependency');
    else if ('react' in dep || 'next' in dep) add('react-web', 'React dependency');
    else if (Object.keys(dep).length || pkg.scripts) add('node-general', 'Node package manifest');
    if ('pg' in dep || '@prisma/adapter-pg' in dep)
      add('postgresql', 'PostgreSQL driver dependency');
    if ('redis' in dep || 'socket.io' in dep) add('redis-events', 'Redis/Socket.IO dependency');
    if ('@modelcontextprotocol/sdk' in dep) add('mcp-server', 'MCP SDK dependency');
  }
  if (name === 'pom.xml' && /spring-boot/iu.test(content)) add('java-spring', 'Spring Boot Maven');
  if (/^build\.gradle/u.test(name)) {
    if (/com\.android\.(application|library)/u.test(content))
      add('android-kotlin', 'Android Gradle');
    else if (/org\.springframework\.boot/u.test(content)) add('java-spring', 'Spring Boot Gradle');
  }
  if (name === 'build.sbt') add('scala-akka', 'Scala manifest');
  if (name === 'Package.swift' || name === 'project.yml') add('ios-swift', 'Swift manifest');
  if (name === 'pyproject.toml' || name === 'requirements.txt') add('python', 'Python manifest');
  if (name === 'Dockerfile' || /compose\.ya?ml$/u.test(name))
    add('docker-local', 'Docker/Compose manifest');
}
const explicit = config.agents?.specialization?.profiles ?? [];
if (!Array.isArray(explicit) || explicit.some((id) => !Object.hasOwn(catalog.profiles, id)))
  throw new Error('Unknown explicit profile');
const ids = [...new Set([...signals.map((s) => s.id), ...explicit])]
  .filter((id) => Object.hasOwn(catalog.profiles, id))
  .sort();
const expandHome = (value) =>
  value.startsWith('~/') || value.startsWith('~\\')
    ? path.join(os.homedir(), value.slice(2))
    : path.resolve(target, value);
const display = (file) => {
  const rel = path.relative(os.homedir(), file);
  return rel && !rel.startsWith('..') && !path.isAbsolute(rel)
    ? '~/' + rel.replaceAll('\\', '/')
    : portable(file);
};
const roots = [
  ['.claude/skills', 'project'],
  ['.agents/skills', 'project'],
  ['skills', 'project'],
  ...(config.skills?.roots ?? ['~/.claude/skills', '~/.agents/skills', '~/.codex/skills']).map(
    (root) => [root, 'user'],
  ),
].map(([root, source]) => ({ root: expandHome(root), source }));
for (const configured of config.skills?.pluginRoots ?? []) {
  const base = expandHome(configured);
  if (!existsSync(base)) continue;
  for (const version of readdirSync(base, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.isSymbolicLink())
    .map((e) => e.name)
    .sort((a, b) => b.localeCompare(a, undefined, { numeric: true })))
    roots.push({ root: path.join(base, version, 'skills'), source: 'ECC-plugin-cache', version });
}
const cache = new Map();
function skillLocation(name) {
  if (!slug.test(name)) throw new Error('Unsafe skill name');
  if (cache.has(name)) return cache.get(name);
  const origin = (catalog.skillOrigins.custom ?? []).includes(name)
    ? 'extension-local'
    : (catalog.skillOrigins.eccReference ?? []).includes(name)
      ? 'ECC-candidate'
      : 'candidate-verify';
  let found;
  for (const root of roots) {
    const file = path.join(root.root, name, 'SKILL.md');
    if (existsSync(file) && lstatSync(file).isFile()) {
      found = {
        name,
        origin,
        location: display(file),
        source: root.source,
        ...(root.version ? { version: root.version } : {}),
        status: 'AVAILABLE_FILE',
        runtimeRegistration: 'NOT_VERIFIED',
        executed: false,
      };
      break;
    }
  }
  const result = found ?? {
    name,
    origin,
    location: null,
    status: 'MISSING',
    runtimeRegistration: 'NOT_VERIFIED',
    executed: false,
  };
  cache.set(name, result);
  return result;
}
function safeTarget(relative) {
  const full = path.resolve(target, relative),
    rel = path.relative(target, full);
  if (!rel || rel.startsWith('..') || path.isAbsolute(rel))
    throw new Error('Output escapes project');
  let current = target;
  for (const part of ['', ...rel.split(path.sep)]) {
    if (part) current = path.join(current, part);
    if (existsSync(current) && lstatSync(current).isSymbolicLink())
      throw new Error('Symlink output refused');
  }
  return full;
}
const desired = [],
  roleSkills = {},
  roleProfiles = {};
for (const role of roles) {
  const selected = config.agents?.specialization?.roleProfiles?.[role];
  if (
    selected &&
    (!Array.isArray(selected) || selected.some((id) => !Object.hasOwn(catalog.profiles, id)))
  )
    throw new Error('Unknown scoped profile');
  const relevant = ['coordinator', 'requirements-analyst'].includes(role)
    ? []
    : ids.filter((id) => !selected || selected.includes(id));
  roleProfiles[role] = relevant;
  let required = [...catalog.roleSkills[role]];
  for (const id of relevant) {
    let skills = catalog.profiles[id].skills;
    if (role === 'qa-engineer')
      skills = skills.filter((s) => /test|qa|verification|accessibility|security/u.test(s));
    else if (['ux-designer', 'design-reviewer'].includes(role))
      skills = skills.filter((s) => /design|frontend-a11y|accessibility|ui-craft/u.test(s));
    else if (role === 'security-reviewer') skills = skills.filter((s) => /security/u.test(s));
    required.push(...skills);
  }
  required = [...new Set([...required, ...(config.skills?.required ?? [])])];
  const skills = required.map(skillLocation);
  roleSkills[role] = required;
  const contract = readFileSync(path.join(sourceRoot, 'agents/roles', role + '.md'), 'utf8');
  const profiles =
    relevant
      .map((id) => `### ${catalog.profiles[id].label} (${id})\n${catalog.profiles[id].guidance}`)
      .join('\n\n') || 'Sin perfil tecnológico para este rol; consultar las fuentes del encargo.';
  const content = `${marker}\n# ${role} — perfil contextual\n\nLeer [guía compartida](../../COMO-TRABAJAMOS.md) y [reglas ACC](../../docs/process/PROJECT-RULES.md). Las decisiones explícitas del proyecto prevalecen. Este perfil no crea una identidad ACC ni ejecuta agentes.\n\n## Contrato de rol\n${contract}\n\n## Tecnologías y alcance\n${profiles}\n\n## Skills candidatas: disponibilidad de archivos\n${skills.map((s) => `- \`${s.name}\` [${s.origin}]: ${s.location ? `DISPONIBLE en \`${s.location}\` (${s.source}); registro del runtime no certificado` : 'NO ENCONTRADA; no afirmar aplicación'}`).join('\n')}\n\nSeleccionar solo las skills pertinentes al módulo/encargo y leerlas antes de aplicarlas. No instalar ni ejecutar automáticamente. Conservar estados IN_REVIEW/IN_QA, autonomía del agente y OK humano posterior a DONE. No elevar permisos del encargo.\n`;
  desired.push({ path: `agents/generated/${role}.md`, content });
  if (role !== 'coordinator')
    desired.push({
      path: `.claude/agents/${role}.md`,
      content: `---\nname: ${role}\ndescription: Especialista ${role} de ACC; respeta el encargo, permisos y fuentes compartidas.\n---\n${marker}\n\nLee \`agents/generated/${role}.md\`, \`COMO-TRABAJAMOS.md\` y \`config/project.json\` desde la raíz del proyecto. Usa \`agents/templates/RESULT.md\` al entregar. La definición no autoriza delegaciones, instalaciones, Git, despliegues ni un OK humano.\n`,
    });
}
const skills = [...cache.values()].sort((a, b) => a.name.localeCompare(b.name));
const detection = {
  managedBy,
  schemaVersion: 2,
  target: '.',
  detectedProfiles: ids,
  signals,
  roles,
  roleProfiles,
  roleSkills,
  skills,
  skillsMissing: skills.filter((s) => !s.location).map((s) => s.name),
  note: 'Solo manifiestos e inventario de archivos; no instala skills ni ejecuta agentes/modelos. Codex usa AGENTS; Claude requiere runtime compatible.',
};
desired.push({
  path: 'agents/generated/DETECTION.json',
  content: JSON.stringify(detection, null, 2) + '\n',
  json: true,
});
for (const item of desired) safeTarget(item.path);
const generated = [],
  skipped = [],
  stale = [];
for (const item of desired) {
  const full = safeTarget(item.path),
    exists = existsSync(full),
    current = exists ? readFileSync(full, 'utf8') : null;
  let currentJson;
  try {
    currentJson = item.json && exists ? JSON.parse(current) : undefined;
  } catch {
    currentJson = undefined;
  }
  const owned = item.json
    ? currentJson?.managedBy === managedBy
    : current?.startsWith(marker) ||
      (current?.startsWith('---\nname:') && current.includes('\n' + marker + '\n'));
  const same = item.json
    ? JSON.stringify(currentJson) === JSON.stringify(detection)
    : current === item.content;
  if (!same) stale.push(item.path);
  if (check) continue;
  if (!write) {
    generated.push(item.path);
    continue;
  }
  if (exists && (!force || !owned)) {
    skipped.push({
      path: item.path,
      reason: owned
        ? 'already exists; use --force for managed files'
        : 'unmanaged file; never overwrite',
    });
    continue;
  }
  mkdirSync(path.dirname(full), { recursive: true });
  writeFileSync(full, item.content, { encoding: 'utf8', flag: exists ? 'w' : 'wx' });
  generated.push(item.path);
}
const report = {
  ...detection,
  mode: check ? 'check' : write ? 'write' : 'dry-run',
  generated,
  skipped,
  stale: check ? stale : [],
};
if (args.includes('--json')) process.stdout.write(JSON.stringify(report, null, 2) + '\n');
else {
  console.log(
    `Stack: ${ids.join(', ') || 'sin detectar'} | roles: ${roles.length} | modo: ${report.mode} | archivos: ${generated.length} | omitidos: ${skipped.length}`,
  );
  if (detection.skillsMissing.length)
    console.log('Skills no encontradas: ' + detection.skillsMissing.join(', '));
  if (check && stale.length) console.log('Archivos faltantes/desactualizados: ' + stale.join(', '));
  if (!write && !check)
    console.log('Diagnóstico sin escrituras; --write requiere encargo autorizado.');
}
if (check && stale.length) process.exitCode = 1;
